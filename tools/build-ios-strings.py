#!/usr/bin/env python3
"""The iPhone app's texts from i18n/strings.json (read-only: never writes into i18n/ or site/).

Usage: python3 tools/build-ios-strings.py <out-json> <out-swift>
- <out-json>: {key: {lang: text or {form: text}}} for he, en, ru and ka, read at runtime by GudiDomain's `Strings`,
  so the language changes inside the app (decision 47) without the system's .lproj folders.
- <out-swift>: typed accessors, one per key, so a missing key or a wrong placeholder is a compile error rather than a
  crash (the lesson of run.videos_search_youtube on Android, 7.10.2026). "run.videos_search_youtube" with {name} and
  {resort} becomes `S.runVideosSearchYoutube(name:resort:)`; a plural takes `count:`, which also fills {n}.
Both outputs are generated and not in the repo (app/ios/.gitignore).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGS = ["he", "en", "ru", "ka"]
# The crew's real first names in the games are the website's (decisions 27 and 55)
SKIP = re.compile(r"^game\.[a-z]+\.friend_")
PH = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")


def ident(key):
    parts = re.split(r"[._]", key)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.fullmatch(r"[a-z][A-Za-z0-9]*", out):
        raise SystemExit(f"bad key for Swift: {key}")
    return out


def placeholders(entry):
    seen = []
    for lang in LANGS:
        t = entry[lang]
        for form in (t.values() if isinstance(t, dict) else [t]):
            for p in PH.findall(form):
                if p not in seen:
                    seen.append(p)
    return seen


def main(out_json, out_swift):
    strings = json.loads((ROOT / "i18n/strings.json").read_text(encoding="utf-8"))["strings"]
    table, funcs, names = {}, [], {}
    for key in sorted(strings):
        if SKIP.match(key):
            continue
        e = strings[key]
        table[key] = {l: e[l] for l in LANGS}
        name = ident(key)
        if name in names:
            raise SystemExit(f"{key} and {names[name]} give the same Swift name {name}")
        names[name] = key
        plural = isinstance(e["he"], dict)
        ps = placeholders(e)
        if plural and "n" in ps:
            ps.remove("n")
        params = (["count: Int"] if plural else []) + [f"{p} a{i}: String" for i, p in enumerate(ps)]
        args = "[" + ", ".join(f'"{p}": a{i}' for i, p in enumerate(ps)) + "]" if ps else "[:]"
        count = "count: count, " if plural else ""
        if params:
            funcs.append(f'    static func {name}({", ".join(params)}) -> String {{ Strings.shared.text("{key}", {count}{args}) }}')
        else:
            funcs.append(f'    static var {name}: String {{ Strings.shared.text("{key}") }}')
    Path(out_json).parent.mkdir(parents=True, exist_ok=True)
    Path(out_json).write_text(json.dumps(table, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    Path(out_swift).parent.mkdir(parents=True, exist_ok=True)
    Path(out_swift).write_text(
        "// Generated by tools/build-ios-strings.py from i18n/strings.json. Do not edit.\n"
        "import GudiDomain\n\n/// Every text of the app, typed. A new text goes into i18n/strings.json first.\nenum S {\n"
        + "\n".join(funcs) + "\n}\n", encoding="utf-8")
    print(f"{len(table)} texts, {len(LANGS)} languages")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
