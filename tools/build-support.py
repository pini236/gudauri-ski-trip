#!/usr/bin/env python3
"""Builds the support page of the site (site/support.html, served at /support) from i18n/strings.json (support.*).

The design is round 33 in the canvas (design/round33/, approved by Pini on 31.10.2026): the same shell as the privacy
page (header, four-language switch, back to about, js/privacy.js picks the language), the support address in a white
card under fresh snow, the "we are not the ski resort" sign, five common questions that open on a tap (<details>, no
script needed), and links to /privacy and /account. Apple needs this page as the app's Support URL (docs/APPLE.md 5.6).
The words live only in i18n/strings.json; edit them there and run this again. tests/support.spec.ts fails if the page
and the strings differ. Run from the repo root: python3 tools/build-support.py"""
import html, importlib.util, json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
OUT = root / 'site/support.html'
_spec = importlib.util.spec_from_file_location('build_privacy', root / 'tools/build-privacy.py')
privacy = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(privacy)
LANGS, MAIL = privacy.LANGS, privacy.MAIL
SEED = {'he': 7, 'en': 11, 'ru': 15, 'ka': 19}  # a drift of snow of its own for each language (site/js/snow.js)
FAQ = 5

ICON = {
    'mail': '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><rect x="3" y="5" width="18" height="14"/><path d="M3 6l9 7 9-7"/></svg>',
    'chev': '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>',
    'lock': '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><rect x="5" y="11" width="14" height="10"/><path d="M8 11V7a4 4 0 0 1 8 0v4"/></svg>',
    'bin': '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M4 7h16M9 7V4h6v3M6 7l1 13h10l1-13"/></svg>',
    'back': '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M5 12h14"/><path d="M13 6l6 6-6 6"/></svg>',
}


def strings():
    return json.loads((root / 'i18n/strings.json').read_text(encoding='utf-8'))['strings']


def esc(s):
    return html.escape(s, quote=False)


def doc(S, lang):
    t = lambda k: esc(S['support.' + k][lang])
    acct = '<a href="/account" dir="ltr">gudauri-ski-trip.vercel.app/account</a>'
    faq = ''.join(f'<details><summary><span>{t(f"faq{i}_q")}</span>{ICON["chev"]}</summary>'
                  f'<p>{t(f"faq{i}_a").replace("{account}", acct)}</p></details>' for i in range(1, FAQ + 1))
    return f'''<article class="pv-doc" id="{lang}" lang="{lang}" dir="{'rtl' if lang == 'he' else 'ltr'}">
<h1>{t('title')}</h1>
<p class="pv-intro">{t('intro')}</p>
<section class="sp-mail" data-snow="{SEED[lang]}" data-snow-pile><h2>{t('mail_title')}</h2>
<a class="sp-addr" href="mailto:{MAIL}">{MAIL}</a><a class="sp-btn" href="mailto:{MAIL}">{ICON['mail']}<span>{t('mail_btn')}</span></a>
<p class="sp-tip">{t('mail_tip')}</p></section>
<div class="pv-sign"><b>{t('sign_title')}</b><span>{t('sign_text')}</span></div>
<section class="sp-faq"><h2>{t('faq_title')}</h2>{faq}</section>
<section class="sp-more"><h2>{t('links_title')}</h2><div class="sp-links"><a href="/privacy#{lang}">{ICON['lock']}<span>{t('link_privacy')}</span></a><a href="/account">{ICON['bin']}<span>{t('link_delete')}</span></a></div></section>
</article>'''


def build():
    S = strings()
    buttons = '\n    '.join(f'<button type="button" data-lang="{l}" aria-pressed="{str(l == "he").lower()}" lang="{l}" aria-label="{full}">{short}</button>'
                            for l, _h, short, full, _b in LANGS)
    backs = ''.join(f'<span data-back="{l}" lang="{l}"{"" if l == "he" else " hidden"}>{b}</span>' for l, _h, _s, _f, b in LANGS)
    docs = '\n'.join(doc(S, l) for l, *_ in LANGS)
    title = ' · '.join([S['support.title']['he'], S['support.title']['en']])
    desc = ' '.join([S['support.meta_desc']['he'], S['support.meta_desc']['en']])
    return f'''<!doctype html>
<!-- Generated by tools/build-support.py from i18n/strings.json (support.*). Do not edit here. -->
<html lang="he" dir="rtl" class="pv">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>{esc(title)} · Gudi: Gudauri Ski Map</title>
<meta name="description" content="{html.escape(desc)}">
<link rel="canonical" href="https://gudauri-ski-trip.vercel.app/support">
<meta name="theme-color" content="#EEF2F5" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0D1522" media="(prefers-color-scheme: dark)">
<link rel="icon" href="favicon-32.png" type="image/png" sizes="32x32">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Karantina:wght@700&family=IBM+Plex+Sans+Hebrew:wght@400;500;600;700&family=IBM+Plex+Sans:wght@400;600;700&family=Oswald:wght@500;600;700&family=Noto+Sans+Georgian:wdth,wght@62.5..100,400..800&display=swap">
<link rel="stylesheet" href="css/site.css">
<script src="js/prefs.js"></script>
<script src="js/telemetry.js" data-screen="support"></script>
<script src="js/snow.js" defer></script>
</head>
<body>
<header class="pv-top">
  <a class="pv-brand" href="/">גודאורי</a>
  <div class="pv-lang" role="group" aria-label="שפה · Language">
    {buttons}
  </div>
  <a class="pv-back" href="/#about">{ICON['back']}{backs}</a>
</header>
<main class="pv-main">
{docs}
<p class="pv-foot"><span dir="ltr">gudauri-ski-trip.vercel.app/support</span></p>
</main>
<script src="js/privacy.js"></script>
</body>
</html>
'''


if __name__ == '__main__':
    OUT.write_text(build(), encoding='utf-8')
    print('wrote', OUT.relative_to(root))
